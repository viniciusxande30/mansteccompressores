                <h3>Como a perda de carga afeta o custo operacional?</h3>

                <p>
                    Quando a rede perde pressao, o compressor precisa operar em um setpoint mais alto para entregar a pressao minima exigida no ponto de uso. Isso eleva o consumo eletrico e pode reduzir a vida util dos componentes.
                </p>

                <p>
                    Em termos praticos, cada ajuste adicional de pressao pode representar mais custo ao longo do ano. Por isso, controlar a perda de carga e uma das maneiras mais rapidas de melhorar a eficiencia energetica.
                </p>

                <h4>Consequencias mais comuns</h4>

                <ul>
                    <li>Maior consumo de energia</li>
