                        <h4>Como funciona um compressor de parafuso?</h4>

                        <p>
                            O compressor de parafuso comprime o ar por meio de dois rotores helicoidais que giram em sentidos opostos. À medida que o ar entra no conjunto compressor, ele é conduzido entre os rotores e tem seu volume reduzido até atingir a pressão de trabalho.
                        </p>

                        <p>
                            Esse processo permite operação contínua, menor pulsação de ar e maior eficiência em demandas industriais. Em modelos lubrificados, o óleo auxilia na vedação, refrigeração e lubrificação. Em aplicações especiais, também existem compressores isentos de óleo.
                        </p>

