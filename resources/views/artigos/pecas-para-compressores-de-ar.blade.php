                            <li><strong>Filtro de óleo:</strong> mantém a lubrificação limpa e reduz desgaste interno.</li>
                            <li><strong>Separador ar/óleo:</strong> reduz arraste de óleo e melhora a qualidade do ar.</li>
                            <li><strong>Óleo lubrificante:</strong> controla temperatura, atrito e vida útil do conjunto compressor.</li>
                            <li><strong>Correias e acoplamentos:</strong> garantem transmissão eficiente de potência.</li>
                            <li><strong>Válvulas, sensores e juntas:</strong> ajudam no controle, vedação e segurança operacional.</li>
