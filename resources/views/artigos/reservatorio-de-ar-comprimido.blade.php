                <h3>Como dimensionar o reservatorio de ar comprimido?</h3>

                <p>
                    O dimensionamento depende de varios fatores: vazao do compressor, perfil de consumo, pressao de trabalho, distancia entre geracao e consumo e variacoes da demanda ao longo do dia.
                </p>

                <p>
                    Em ambientes com consumo oscilante, o tanque precisa ter volume suficiente para absorver picos sem provocar queda acentuada de pressao. Ja em plantas com demanda mais estavel, o objetivo e desacoplar a producao do consumo e manter a linha mais equilibrada.
                </p>

                <h4>O que avaliar no projeto</h4>

                <ul>
                    <li>Capacidade do compressor principal</li>
                    <li>Tempo de resposta desejado para picos de consumo</li>
                    <li>Quantidade de pontos de uso simultaneos</li>
                    <li>Queda de pressao aceitavel no processo</li>
                    <li>Espaco fisico para instalacao e manutencao</li>
                    <li>Integracao com filtros, secadores e rede de distribuicao</li>
                </ul>

                <h3>Erros comuns que prejudicam a eficiencia</h3>

                <p>
                    Escolher o tanque apenas pelo tamanho fisico ou por estimativa rapida costuma gerar problemas. O mesmo vale para instalar o reservatorio sem drenagem adequada, sem analise do layout ou sem manutencao periodica.
                </p>

                <ul>
                    <li>Tanque subdimensionado para a demanda real</li>
                    <li>Tanque superdimensionado sem necessidade operacional</li>
                    <li>Instalacao em local de dificil acesso</li>
                    <li>Ausencia de drenagem de condensado</li>
                    <li>Falta de integracao com o controle do compressor</li>
                </ul>

                <h3>Reservatorio e seguranca operacional</h3>

                <p>
                    Como trabalha sob pressao, o reservatorio deve ser tratado com criterio tecnico. Inspecao visual, integridade mecanica, drenagem e conformidade com normas aplicaveis fazem parte da rotina de seguranca.
                </p>

                <p>
