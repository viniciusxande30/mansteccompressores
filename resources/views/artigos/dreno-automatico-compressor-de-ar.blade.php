                <h3>Tipos mais comuns de dreno automático</h3>

                <p>
                    Nem todo dreno atua da mesma forma. A escolha correta depende do volume de condensado, da criticidade da aplicação e do nível de confiabilidade exigido pela operação.
                </p>

                <ol>
                    <li><strong>Dreno manual:</strong> exige abertura periódica feita por um operador.</li>
                    <li><strong>Dreno por temporização:</strong> abre em intervalos definidos, mesmo sem medir o nível de condensado.</li>
                    <li><strong>Dreno eletrônico por nível:</strong> identifica o acúmulo real e descarrega apenas quando necessário.</li>
                    <li><strong>Dreno de perda zero:</strong> ajuda a evitar desperdício de ar comprimido durante a descarga do condensado.</li>
